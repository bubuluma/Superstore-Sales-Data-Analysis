import os
import pandas as pd
from google.colab import files

def run_export():
    global df
    # 1. Load the original dataset with correct columns
    print("Loading dataset...")
    df = pd.read_excel("train.xlsx", sheet_name="train", usecols="A:R")

    # 2. Re-apply cleaning steps
    print("Cleaning missing sales and removing duplicates...")
    df = df.dropna(subset=["Sales"])
    df = df.drop_duplicates()

    # 3. Re-apply format conversions
    print("Formatting dates and data types...")
    df["Order Date"] = pd.to_datetime(df["Order Date"], dayfirst=True, errors="coerce")
    df["Ship Date"] = pd.to_datetime(df["Ship Date"], dayfirst=True, errors="coerce")
    df["Postal Code"] = df["Postal Code"].astype("string")
    df["Sales"] = pd.to_numeric(df["Sales"], errors="coerce")

    # 4. Re-create calculated analytical columns
    print("Extracting analytical fields...")
    df["Shipping Days"] = (df["Ship Date"] - df["Order Date"]).dt.days
    df["Order Year"] = df["Order Date"].dt.year
    df["Order Month"] = df["Order Date"].dt.month
    df["Month Name"] = df["Order Date"].dt.month_name()
    df["Year Month"] = df["Order Date"].dt.to_period("M").astype(str)

    # 5. Export and Download cleaned dataset
    print("Exporting cleaned datasets...")
    df.to_csv("/content/Superstore_Cleaned.csv", index=False)
    df.to_excel("/content/Superstore_Cleaned.xlsx", index=False)
    print("Triggering file download...")
    files.download("/content/Superstore_Cleaned.csv")

